#!/usr/bin/env node
// Layer 0 of agent-workflow.md: generated context, never hand-written.
// Walks the registry + @rata/react source + @rata/tokens' build output and
// writes .claude/ui-context.md — a single file an agent (or a human, pasting
// into a chat window) can read instead of recalling the component API from
// memory. Re-run via `npm run ui:sync`; `npm run build` does this as its
// last step, so it's always in sync with a fresh `npm install && npm run build`.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  repoRoot,
  loadRegistry,
  sortedEntries,
  getComponentProps,
  getTokens,
  getPages,
} from "../packages/cli/lib/index.mjs";

// Every props section links out to the component's full contract page — the
// terse list here answers "what are the props", the page answers "what is each
// one FOR". Both come from the same two sources; neither is hand-written.
const contractLink = (name) => `Contract: [docs/components/${name}.md](../docs/components/${name}.md)`;

function renderPropsSection(result) {
  if (!result.implemented) {
    return `### ${result.title ?? result.name}\n\n${result.note}\n\n${contractLink(result.name)}\n`;
  }
  const lines = [`### ${result.title} (\`${result.importPath}\`)`, ""];
  if (result.extends) lines.push(`Extends: \`${result.extends}\``, "");
  for (const prop of result.props) {
    const def = prop.default !== undefined ? ` — default: \`${prop.default}\`` : "";
    lines.push(`- \`${prop.name}${prop.optional ? "?" : ""}: ${prop.type}\`${def}`);
    if (prop.description) lines.push(`  ${prop.description}`);
  }
  if (result.example) {
    lines.push("", "Real usage (from `apps/`):", "```tsx", result.example, "```");
  }
  lines.push("", contractLink(result.name));
  return lines.join("\n") + "\n";
}

async function main() {
  const registry = await loadRegistry();
  const entries = sortedEntries(registry);
  const tokens = await getTokens();
  const pages = await getPages();

  const componentRows = entries.map((entry) => {
    const css = entry.status?.css?.state ?? "tbd";
    const react = entry.status?.react?.state ?? "tbd";
    const figma = entry.status?.figma?.state ?? "tbd";
    return `| [${entry.name}](../docs/components/${entry.name}.md) | \`@rata/react\` | ${entry.family} | ${css} / ${react} / ${figma} | ${entry.tier ?? "free"} |`;
  });

  const propsSections = [];
  for (const entry of entries) {
    const result = await getComponentProps(entry.name, registry);
    propsSections.push(renderPropsSection(result));
  }

  const tokenLines = tokens
    ? Object.entries(tokens)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([key, value]) => `- \`--rata-${key}\`: \`${value}\``)
    : ["_Not built yet — run `npm run build -w @rata/tokens` and regenerate._"];

  const pageLines = pages.length
    ? pages.map((page) => `- \`${page.path}\` — shell: ${page.shell}`)
    : ["_No page entry-points found under `apps/*/src`._"];

  const md = `# UI context — generated, do not edit by hand

Generated by \`npm run ui:sync\` (scripts/generate-ui-context.mjs) from the
registry, \`@rata/react\` source, and \`@rata/tokens\`. Same lookups are also
available live via \`npm run ui -- props|tokens|pages\` (see CLAUDE.md).

Each component name links to its full contract in
[docs/components/](../docs/components/README.md) — what every prop is *for*,
when not to reach for it, and worked use cases. This file is the index; that
is the reference. \`npm run ui -- contract <name>\` prints the same thing.

There is deliberately no generation timestamp here: this file is rewritten by
every build, and a wall-clock stamp made the working tree dirty on every one
of them even when nothing about the components had changed. \`git log\` for
this path is the honest answer to when it last actually moved.

## Components

| Name | Import | Family | Status (css / react / figma) | Tier |
|---|---|---|---|---|
${componentRows.join("\n")}

## Props

${propsSections.join("\n")}
## Tokens

${tokenLines.join("\n")}

## Pages

${pageLines.join("\n")}
`;

  const outDir = path.join(repoRoot, ".claude");
  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, "ui-context.md"), md);
  console.log(`.claude/ui-context.md written — ${entries.length} component(s), ${tokenLines.length} token line(s), ${pages.length} page(s).`);
}

await main();

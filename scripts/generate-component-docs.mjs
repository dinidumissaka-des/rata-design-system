#!/usr/bin/env node
/**
 * @file generate-component-docs.mjs
 * @input registry/components/*.json + packages/react/src/*.tsx, via cli/lib/contract.mjs
 * @output docs/components/<name>.md, one page each, plus an index
 * @position Doc generator; run by `npm run docs:components`, verified by --check
 *
 * The component-layer twin of packages/tokens/build.mjs: a hand-written
 * contract in, a generated page out, and the build fails rather than emitting
 * a page whose written half disagrees with its derived half.
 *
 * Run with --check to fail instead of rewriting when a page is out of date,
 * the same way `npm run docs:check` guards TOKENS.md.
 */
import { mkdir, readFile, writeFile, readdir, rm } from "node:fs/promises";
import path from "node:path";
import { repoRoot, loadRegistry } from "../packages/cli/lib/index.mjs";
import { getAllContracts } from "../packages/cli/lib/contract.mjs";
import { loadTokenModel, evaluateSource } from "../internal/vibe-tests/rules.mjs";

const CHECK_ONLY = process.argv.includes("--check");
const outDir = path.join(repoRoot, "docs/components");

const HEADER = `<!-- GENERATED by scripts/generate-component-docs.mjs — do not edit by hand. -->
<!-- Written half lives in registry/components/<name>.json; derived half is parsed from packages/react/src/<name>.tsx. -->`;

const STATE_NOTE = {
  spec: "**Not implemented yet.** This page is the *approved intent* — the props API signed off at gate 1 of the build order, before any React exists. Do not import it; there is nothing to import.",
  "css-only": "**CSS-only.** There is no React component to import — this is a class composed onto other components.",
};

/** Markdown tables split on bare pipes, and union types are full of them. */
const cell = (text) => String(text).replace(/\|/g, "\\|");

function list(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function renderProp(prop) {
  const lines = [];
  const optional = prop.optional ? "?" : "";
  const def = prop.default !== undefined && prop.default !== null ? ` = ${prop.default}` : "";
  lines.push(`### \`${prop.name}\``, "");
  lines.push("```ts", `${prop.name}${optional}: ${prop.type}${def}`, "```", "");
  if (prop.summary) lines.push(prop.summary, "");
  else if (prop.description) lines.push(prop.description, "");
  if (prop.description && prop.summary && prop.description !== prop.summary) {
    lines.push(`Source doc: ${prop.description}`, "");
  }
  if (prop.use.length) lines.push("**Use when**", "", list(prop.use), "");
  if (prop.dont.length) lines.push("**Don't use for**", "", list(prop.dont), "");
  if (prop.conflicts.length) {
    lines.push(`**Conflicts with** ${prop.conflicts.map((c) => `\`${c}\``).join(", ")}`, "");
  }
  if (prop.a11y) lines.push(`**Accessibility** ${prop.a11y}`, "");
  return lines.join("\n");
}

function renderTokens(tokens) {
  const blocks = [];
  for (const [variant, recipe] of Object.entries(tokens)) {
    blocks.push(`### ${variant}`, "");
    if (recipe.summary) blocks.push(recipe.summary, "");
    blocks.push("| Property | Token |", "|---|---|");
    for (const [property, token] of Object.entries(recipe.tokens ?? {})) {
      blocks.push(`| ${cell(property)} | \`${cell(token)}\` |`);
    }
    blocks.push("");
  }
  return blocks.join("\n");
}

function renderPage(contract) {
  const s = contract.status;
  const state = (artifact) => s?.[artifact]?.state ?? "tbd";
  const lines = [HEADER, "", `# ${contract.title}`, "", contract.description, ""];

  if (STATE_NOTE[contract.mode]) lines.push(STATE_NOTE[contract.mode], "");
  else lines.push("```tsx", `import { ${contract.title.replace(/[^A-Za-z]/g, "")} } from "${contract.importPath}";`, "```", "");

  lines.push(
    "| | |",
    "|---|---|",
    `| Registry name | \`${contract.name}\` |`,
    `| Family | ${contract.family} |`,
    `| Tier | ${contract.tier} |`,
    `| Status (css / react / figma) | ${state("css")} / ${state("react")} / ${state("figma")} |`,
    `| Depends on | ${contract.dependencies.length ? contract.dependencies.map((d) => `\`${d}\``).join(", ") : "—"} |`,
    ""
  );

  if (contract.behavior) {
    lines.push("## Behavior", "");
    if (contract.behavior.summary) lines.push(contract.behavior.summary, "");
    if (contract.behavior.primitive) {
      lines.push(
        `Headless contract: \`${contract.behavior.primitive}\` in ` +
          `\`packages/primitives/src/${contract.name}.ts\` — importable from \`@rata/primitives\` ` +
          `without the React wrapper or any CSS.`,
        ""
      );
    }
    for (const decision of contract.behavior.decisions ?? []) {
      lines.push(`- **${decision.decision}** — ${decision.why}`);
    }
    if (contract.behavior.decisions?.length) lines.push("");
  }

  if (contract.props.length) {
    lines.push("## Props", "");
    if (contract.extends) lines.push(`Extends \`${contract.extends}\`.`, "");
    lines.push("| Prop | Type | Default | Summary |", "|---|---|---|---|");
    for (const prop of contract.props) {
      const def = prop.default !== undefined && prop.default !== null ? `\`${prop.default}\`` : "—";
      lines.push(
        `| \`${prop.name}${prop.optional ? "?" : ""}\` | \`${cell(prop.type)}\` | ${cell(def)} | ${cell(prop.summary ?? prop.description ?? "—")} |`
      );
    }
    lines.push("");
    for (const prop of contract.props) lines.push(renderProp(prop));
  } else if (contract.mode !== "css-only") {
    lines.push("## Props", "", "_None documented yet._", "");
  }

  if (contract.usage.length) {
    lines.push("## Use cases", "");
    for (const item of contract.usage) {
      lines.push(`### ${item.case}`, "");
      if (item.when) lines.push(item.when, "");
      if (item.example) lines.push("```tsx", item.example, "```", "");
      if (item.notes) lines.push(item.notes, "");
    }
  }

  if (contract.example) {
    lines.push("## Real usage in this repo", "", "```tsx", contract.example, "```", "");
  }

  if (Object.keys(contract.tokens).length) {
    lines.push("## Token recipe", "", renderTokens(contract.tokens));
  }

  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/**
 * The same contracts the pages above render, as data — for readers that are
 * not a person reading Markdown. The playground's component pages consume
 * this, so what an agent reads in docs/components and what a designer clicks
 * through at localhost:5173 are the same assembled contract, not two
 * renderings that can disagree.
 *
 * `issues` is dropped: generation aborts when it is non-empty, so a committed
 * file can only ever carry an empty array.
 */
function renderJson(contracts) {
  const withoutIssues = contracts.map(({ issues: _issues, ...rest }) => rest);
  return JSON.stringify(withoutIssues, null, 2) + "\n";
}

function renderIndex(contracts) {
  const rows = contracts.map((c) => {
    const react = c.status?.react?.state ?? "tbd";
    const css = c.status?.css?.state ?? "tbd";
    return `| [${c.title}](${c.name}.md) | \`${c.name}\` | ${c.family} | ${css} / ${react} | ${c.mode} | ${c.tier} |`;
  });
  return [
    HEADER,
    "",
    "# Component contracts",
    "",
    "One page per component, generated from that component's registry manifest",
    "(the written half — what each prop is for) and its `@rata/react` source (the",
    "derived half — names, types, defaults). The build fails if the two disagree.",
    "",
    "`mode` is `documented` when the component is implemented and both halves are",
    "cross-checked, `spec` when the contract is an approved intent with no code",
    "behind it yet, and `css-only` when there is no props API by design.",
    "",
    "| Component | Name | Family | Status (css / react) | Mode | Tier |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

/**
 * Lint every worked example against the same token rules that score generated
 * component code. This cannot tell whether the advice is *good*; what it does
 * catch is an example that contradicts the token discipline the rest of the
 * documentation preaches — a hardcoded hex, a hand-rolled :hover, a palette
 * token used directly. An example is the part of a contract most likely to be
 * copied verbatim, so it is the part least affordable to leave unchecked.
 *
 * Only presence-based rules apply. A contract example is a fragment, not a
 * component, so the absence of something is not evidence: "no :focus-visible
 * ring here" is true of every JSX snippet ever written and says nothing about
 * the component the snippet uses. Rules that fire on something *present* —
 * a hex, a palette token, a hardcoded duration, an `outline: none` — stay on.
 */
const ABSENCE_RULES = new Set(["missing-focus-ring", "focus-not-visible-scoped"]);

function lintExamples(contract, model) {
  const found = [];
  for (const item of contract.usage) {
    if (!item.example) continue;
    const { violations } = evaluateSource(item.example, model, { filename: contract.name });
    for (const v of violations) {
      if (v.severity !== "error" || ABSENCE_RULES.has(v.rule)) continue;
      found.push(
        `${contract.name}.usage["${item.case}"].example [${v.rule}] ${v.message}`
      );
    }
  }
  return found;
}

async function main() {
  const registry = await loadRegistry();
  const contracts = await getAllContracts(registry);

  // Null when tokens haven't been built yet — skip the example lint rather
  // than fail, the same way getTokens() degrades.
  let model = null;
  try {
    model = loadTokenModel();
  } catch {}
  if (model) {
    for (const contract of contracts) contract.issues.push(...lintExamples(contract, model));
  }

  const issues = contracts.flatMap((c) => c.issues);
  if (issues.length) {
    console.error("Component contracts are inconsistent with their source:\n");
    for (const issue of issues) console.error(`  ✗ ${issue}`);
    console.error(
      "\nEach of these is a written contract and a derived API disagreeing. Fix the manifest\n" +
        "or the component — don't delete the check."
    );
    process.exitCode = 1;
    return;
  }

  const pages = new Map(contracts.map((c) => [`${c.name}.md`, renderPage(c)]));
  pages.set("README.md", renderIndex(contracts));
  pages.set("contracts.json", renderJson(contracts));

  if (CHECK_ONLY) {
    const stale = [];
    for (const [file, content] of pages) {
      let current = null;
      try {
        current = await readFile(path.join(outDir, file), "utf8");
      } catch {
        stale.push(`${file} (missing)`);
        continue;
      }
      if (current !== content) stale.push(file);
    }
    let extra = [];
    try {
      extra = (await readdir(outDir)).filter((f) => f.endsWith(".md") && !pages.has(f));
    } catch {}
    for (const file of extra) stale.push(`${file} (no longer has a manifest)`);

    if (stale.length) {
      console.error(`docs/components is out of date: ${stale.join(", ")}`);
      console.error("Run `npm run docs:components` and commit the result.");
      process.exitCode = 1;
      return;
    }
    console.log(`docs/components is current — ${contracts.length} component page(s).`);
    return;
  }

  await mkdir(outDir, { recursive: true });
  let existing = [];
  try {
    existing = (await readdir(outDir)).filter((f) => f.endsWith(".md"));
  } catch {}
  for (const file of existing) {
    if (!pages.has(file)) await rm(path.join(outDir, file));
  }
  for (const [file, content] of pages) {
    await writeFile(path.join(outDir, file), content);
  }
  console.log(`docs/components written — ${contracts.length} page(s) + index.`);
}

await main();
